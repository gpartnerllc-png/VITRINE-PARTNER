export const ASSET_VERSION = "20261101";

export const CATALOG = RAW.map((p, index) => {
  const cat = CATEGORIES.find((c) => c.id === p.category) || CATEGORIES[0];
  const offers = p.offers.map((offer, i) => ({ ...offer, id: `${p.id}:${i + 1}` }));
  return {
    ...p,
    order: index,
    image: `assets/products/${p.id}.webp?v=${ASSET_VERSION}`,
    imageSmall: `assets/products/${p.id}-480.webp?v=${ASSET_VERSION}`,
    imageAlt: p.imageAlt || `${p.name} — ${p.tagline}`,
    categoryLabel: cat.label,
    categoryShort: cat.short,
    categoryColor: cat.color,
    offerCount: offers.length,
    primaryUrl: offers[0].url,
    search: [p.name, p.tagline, p.desc, cat.label, ...p.tags, ...offers.map((x) => x.label)].join(" ").toLowerCase(),
    offers,
  };
});

export const FEATURED = CATALOG.filter((p) => p.featured);
export const TOTAL_OFFERS = CATALOG.reduce((sum, p) => sum + p.offerCount, 0);

export function findProduct(id) {
  return CATALOG.find((p) => p.id === id) || null;
}

export function findOfferByUrl(url) {
  for (const product of CATALOG) {
    const offer = product.offers.find((x) => x.url === url);
    if (offer) return { product, offer };
  }
  return null;
}

export const CATEGORY_COUNTS = CATEGORIES.map((cat) => ({
  ...cat,
  count: CATALOG.filter((p) => p.category === cat.id).length,
}));
